"""Generate derived registries and traceability from authority data.

Inputs (authority data, hand-maintained or lock-protected):
    protocols/*.json                               (lock-verified via apgi.protocols)
    specifications/model/parameter-registry.yaml
    specifications/model/equations.yaml
    specifications/claims/core-claims.yaml
    gates/gate-table.yaml

Generated (never hand-edit; CI runs ``--check`` and fails on drift):
    specifications/model/observable-registry.yaml   S1-FWK-07
    specifications/model/decision-rule-registry.yaml S1-FWK-03, VAL-001
    specifications/claims/claim-register.yaml       SCI-007, AUD-GOV-05
    traceability/predictions.yaml                   S1-FWK-06.1
    traceability/evidence-map.yaml                  S1-FWK-06.2
    traceability/crosswalk.yaml                     S1-FWK-06
    gates/exposable-fields.yaml                     S1-PR2b-02

Usage:
    python scripts/build_specifications.py          # regenerate
    python scripts/build_specifications.py --check  # exit 1 on drift
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from apgi.protocols import canonical_json, load_protocols, verify_lock  # noqa: E402

HEADER = "# GENERATED by scripts/build_specifications.py — do not edit by hand.\n"

# Observable units, one entry per dependent variable in protocol order.
# unit_status: conventional = the standard unit for this measure;
