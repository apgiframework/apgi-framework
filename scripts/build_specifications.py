PARAM_IDS = {"theta_0": "PAR-THETA-0", "eta": "PAR-ETA-PRECISION", "tau_theta": "PAR-TAU-THETA",
             "gamma_sig": "PAR-GAMMA-SIG", "rho": "PAR-RHO-PRECISION", "Pi_i": "PAR-PI-I-BASELINE",
             "Pi_e": "PAR-PI-E", "beta_SM": "PAR-BETA-SM", "kappa": "PAR-KAPPA", "tau_S": "PAR-TAU-S"}

PREDICTION_STATUS_TO_EPISTEMIC = "speculative"  # registered but untested prediction


def load_yaml(rel: str) -> dict:
    return yaml.safe_load((ROOT / rel).read_text(encoding="utf-8"))


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data: object) -> bool:
        return True


def dump(data: object) -> str:
    return HEADER + yaml.dump(data, Dumper=_NoAliasDumper, sort_keys=False, allow_unicode=True,
                              width=100)


def pnum(pid: str) -> str:
    return pid.split("-")[1]  # "P01"


def pred_key(pred_id: str) -> str:
    # "Pred 1.A" -> "1A"
    match = re.fullmatch(r"Pred (\d+)\.([A-Z])", pred_id)
    if not match:
        raise ValueError(f"unexpected prediction id {pred_id!r}")
    return match.group(1) + match.group(2)


def protocol_file(pid: str, lock: dict) -> str:
    n = pid[-1]
    return next(f"protocols/{name}" for name in lock["files"] if name.startswith(f"protocol_{n}_"))


def build() -> dict[str, str]:
    lock = verify_lock(ROOT / "protocols")
    protocols = load_protocols(ROOT / "protocols")
    params = load_yaml("specifications/model/parameter-registry.yaml")
    equations = {e["id"]: e for e in load_yaml("specifications/model/equations.yaml")["entries"]}
    core_claims = load_yaml("specifications/claims/core-claims.yaml")
    gates = load_yaml("gates/gate-table.yaml")
    param_ids = {e["id"] for e in params["entries"]}

    observables, rules, claims, predictions, evidence, = [], [], [], [], []
    obs_by_protocol: dict[str, list[str]] = {}
    for pid, proto in protocols.items():
        units = UNITS[pid]
        dvs = list(proto["dependent_variables"])
        if len(units) != len(dvs):
            raise SystemExit(f"{pid}: {len(dvs)} dependent variables but {len(units)} unit entries")
        ids = []
        for i, (label, (unit, status)) in enumerate(zip(dvs, units), start=1):
            oid = f"OBS-{pnum(pid)}-{i:02d}"
            ids.append(oid)
            observables.append({"id": oid, "label": label, "unit": unit, "unit_status": status,
                                "protocol_id": pid, "registry_ep": proto["registry_ep"],
                                "linked_task": protocol_file(pid, lock),
                                "exposure_class": "model_free_index"})
        obs_by_protocol[pid] = ids
        for key, text in proto["quality_and_decision_rules"]["scenarios"].items():
            rules.append({"id": f"DR-{pnum(pid)}-SCN-{key}", "protocol_id": pid, "kind": "scenario",
                          "scenario": key, "rule": text,
                          "rule_sha256": hashlib.sha256(canonical_json(text)).hexdigest()})
        for idx, pred in enumerate(proto["sub_predictions"], start=1):
            k = pred_key(pred["id"])
            dr_id, pr_id = f"DR-{pnum(pid)}-{k}", f"PRED-{pnum(pid)}-{k}"
            clm_id = f"CLM-{100 + int(pid[-1]) * 10 + idx:04d}"
            rule_hash = hashlib.sha256(canonical_json(pred)).hexdigest()
            rules.append({"id": dr_id, "protocol_id": pid, "kind": "prediction",
                          "prediction_id": pr_id, "source_id": pred["id"], "status": pred["status"],
                          "confirming": pred.get("confirming_evidence"),
                          "falsifying": pred.get("falsifying_evidence"),
                          "indeterminate": pred.get("indeterminate_rule"),
                          "thresholds": json.loads(canonical_json(pred.get("confirming_thresholds") or {})),
                          "rule_sha256": rule_hash})
            claims.append({"id": clm_id, "statement": pred["claim"], "source": f"{protocol_file(pid, lock)} {pred['id']}; {proto['paper']}",
                           "epistemic_tier": "computational", "status": PREDICTION_STATUS_TO_EPISTEMIC,
                           "status_basis": f"registered {pred['status']} prediction; no empirical result in this repository",
                           "protocol_id": pid, "prediction_id": pr_id})
            reduced = [q for q in proto["apgi_parameters"].get("reduced_quantities", [])]
            predictions.append({
                "id": pr_id, "source_id": pred["id"], "protocol_id": pid,
                "protocol_file": protocol_file(pid, lock), "status": pred["status"],
                "claim": clm_id, "decision_rule": dr_id, "rule_sha256": rule_hash,
                "equations": EQUATIONS[pid], "parameters": sorted({PARAM_IDS[q] for q in reduced}),
                "observables": obs_by_protocol[pid], "observable_mapping": "protocol-level (all registered DVs)",
                "code": sorted({equations[e]["code"] for e in EQUATIONS[pid]}),
                "registered_model_variant": "MV-PROTOCOL-REDUCED-1",
                "implementation_status": "registered formulation not implemented in src/apgi; core model is a different variant",
                "evidence": f"EVM-{pnum(pid)}-{k}"})
            evidence.append({"id": f"EVM-{pnum(pid)}-{k}", "prediction_id": pr_id,
                             "empirical_evidence": "none — study not run (protocol readiness: not submission-ready)",
                             "simulation_evidence": _sim_evidence(pid),
                             "outcome": "pending", "verdict_record": None,
                             "blocking_issues": len(proto.get("submission_blocking_issues", []))})

    for pred in predictions:
        for p in pred["parameters"]:
            if p not in param_ids:
                raise SystemExit(f"{pred['id']}: unknown parameter id {p}")

    claim_register = {"register_version": "0.1.0", "status": "draft_unapproved",
                      "owner": "Scientific authority (Not appointed)",
                      "statuses": ["established", "derived", "calibrated", "speculative"],
                      "tiers": ["thermodynamic", "information_theoretic", "computational"],
                      "claims": core_claims["claims"] + claims}

    crosswalk = []
    for eq_id, eq in equations.items():
        preds = [p["id"] for p in predictions if eq_id in p["equations"]]
        crosswalk.append({"equation": eq_id, "expression": eq["expression"], "source": eq["source"],
                          "code": eq["code"], "fixtures": eq.get("fixtures", []),
                          "protocols": sorted({p["protocol_id"] for p in predictions if eq_id in p["equations"]}),
                          "predictions": preds,
                          "outcome_evidence": sorted({f"EVM-{p.split('-', 1)[1]}" for p in preds})})

    obs_index = {o["id"]: o for o in observables}
    exposable = []
    for entry in gates["gates"]:
        if entry["exposure_class"] in {"model_free_index", "identified_composite", "cleared_parameter"} \
                and entry["status"] == "cleared":
            exposable.append({"field": entry["field"], "registry_id": entry["registry_id"],
                              "exposure_class": entry["exposure_class"]})
    for oid, obs in obs_index.items():
        exposable.append({"field": oid, "registry_id": oid, "exposure_class": "model_free_index",
                          "label": obs["label"]})

    lock_ref = {"protocol_manifest_sha256": lock["manifest_sha256"], "release": lock["release"]}
    out = {
        "specifications/model/observable-registry.yaml": dump({**lock_ref, "registry_version": "0.1.0", "entries": observables}),
        "specifications/model/decision-rule-registry.yaml": dump({**lock_ref, "registry_version": "0.1.0", "immutability": "rule_sha256 is canonical-JSON SHA-256 of the registered rule; any change is a post-registration amendment (VAL-001)", "entries": rules}),
        "specifications/claims/claim-register.yaml": dump(claim_register),
        "traceability/predictions.yaml": dump({**lock_ref, "predictions": predictions}),
        "traceability/evidence-map.yaml": dump({**lock_ref, "evidence": evidence}),
        "traceability/crosswalk.yaml": dump({**lock_ref, "crosswalk": crosswalk}),
        "gates/exposable-fields.yaml": dump({"gate_table_version": gates["gate_table_version"],
                                             "model_version": gates["model_version"],
                                             "policy": "model-free indices, identified composites and cleared parameters only",
                                             "fields": exposable}),
    }
    return out


def _sim_evidence(pid: str) -> list[str]:
    manifest = json.loads((ROOT / "data/seeds/seed_manifest.json").read_text(encoding="utf-8"))
    n = pid[-1]
    return [f"data/seeds/{d['file']} (synthetic; {d.get('v1_1_alignment', 'unknown')} vs v1.1)"
            for d in manifest["datasets"] if d.get("protocol", "").startswith(f"protocols/protocol_{n}_")]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate APGI derived registries")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    drift = []
    for rel, text in build().items():
        path = ROOT / rel
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                drift.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if drift:
        print("generated files out of date (run scripts/build_specifications.py):\n  " + "\n  ".join(drift),
              file=sys.stderr)
        return 1
    print("specifications up to date" if args.check else "specifications regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
