"""Build or check bundle/SHA256SUMS for the APGI specification bundle (S1-FWK-04).

    python scripts/build_spec_bundle.py          # write bundle/SHA256SUMS
    python scripts/build_spec_bundle.py --check  # CI gate XC-CI-01.2: exit 1 on drift
    python scripts/build_spec_bundle.py --verify # consumer verification only
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from apgi.spec_bundle import BundleVerificationError, bundle_files, verify_bundle  # noqa: E402

HEADER = ("# APGI specification bundle (bundle_format 1). Generated by scripts/build_spec_bundle.py.\n"
          "# Verify before use: python -c 'import apgi.spec_bundle as b; b.verify_bundle()'\n")


def render() -> str:
    lines = [f"{hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()}  {rel}" for rel in bundle_files(ROOT)]
    return HEADER + "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true")
    group.add_argument("--verify", action="store_true")
    args = parser.parse_args(argv)
    target = ROOT / "bundle" / "SHA256SUMS"
    if args.verify or args.check:
        try:
            record = verify_bundle(ROOT)
        except BundleVerificationError as exc:
            print(exc, file=sys.stderr)
            return 1
        if args.check and target.read_text(encoding="utf-8") != render():
            print("bundle/SHA256SUMS is out of date (run scripts/build_spec_bundle.py)", file=sys.stderr)
            return 1
        print(f"bundle verified: {record['file_count']} files, SHA256SUMS {record['sha256sums_sha256']}")
        return 0
    target.parent.mkdir(exist_ok=True)
    target.write_text(render(), encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
